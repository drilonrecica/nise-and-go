func TestWriteRefusesHandEditedAgentsMD(t *testing.T) {
	t.Parallel()
	root := t.TempDir()
	r := fullRecipe()

	result, err := agentsfile.Write(root, r, false)
	if err != nil {
		t.Fatalf("first Write: %v", err)
	}

	tamperMarker := "hand-edited by a human, not nise"
	original, err := os.ReadFile(result.AgentsPath)
	if err != nil {
		t.Fatal(err)
	}
	// Insert the marker right after the two header lines, so it lands
	// within the preview's first previewMaxLines lines rather than
	// possibly being truncated away if appended at the very end.
	lines := strings.SplitN(string(original), "\n", 3)
	tampered := lines[0] + "\n" + lines[1] + "\n" + tamperMarker + "\n" + lines[2]
	// #nosec G703 -- result.AgentsPath is this test's own agentsfile.Write
	// return value, joined from t.TempDir() a few lines above; it is not
	// attacker-controlled. gosec's taint analysis flags it only because
	// the path traveled through a struct field, not a literal.
	if err := os.WriteFile(result.AgentsPath, []byte(tampered), 0o644); err != nil {
		t.Fatal(err)
	}

	_, err = agentsfile.Write(root, r, false)
	var conflictErr *agentsfile.ConflictError
	if !errors.As(err, &conflictErr) {
		t.Fatalf("Write after hand edit = %v, want *ConflictError", err)
	}
	if len(conflictErr.Conflicts) != 1 || conflictErr.Conflicts[0].Path != result.AgentsPath {
		t.Errorf("Conflicts = %+v, want exactly one entry for %s", conflictErr.Conflicts, result.AgentsPath)
	}
	if !strings.Contains(conflictErr.Conflicts[0].Preview, "hand-edited by a human") {
		t.Errorf("Preview does not show the tampered content: %q", conflictErr.Conflicts[0].Preview)
	}

	// The architecture map must be untouched: a refusal must not
	// partially apply, leaving one output regenerated and the other not.
	archBefore, err := os.ReadFile(result.ArchitecturePath)
	if err != nil {
		t.Fatal(err)
	}
	if _, err := agentsfile.Write(root, r, false); err == nil {
		t.Fatal("expected the same conflict again")
	}
	archAfter, err := os.ReadFile(result.ArchitecturePath)
	if err != nil {
		t.Fatal(err)
	}
	if string(archBefore) != string(archAfter) {
		t.Error("architecture.json changed despite the refusal")
	}
}

