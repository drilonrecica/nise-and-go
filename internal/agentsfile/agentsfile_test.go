// fullRecipe is a recipe with every module selected, matching the golden
// fixtures under testdata/.
func fullRecipe() recipe.Recipe {
	return recipe.Recipe{
		SchemaVersion:  recipe.SchemaVersion,
		Profile:        recipe.ProfileGoChiPostgresSvelte,
		Modules:        recipe.Modules(),
		CLIVersion:     "v0.1.0",
		RuntimeVersion: "v0.1.0",
	}
}

func TestGenerateIsDeterministic(t *testing.T) {
	t.Parallel()
	r := fullRecipe()

	a, err := agentsfile.Generate(r)
	if err != nil {
		t.Fatalf("Generate: %v", err)
	}
	b, err := agentsfile.Generate(r)
	if err != nil {
		t.Fatalf("Generate: %v", err)
	}

	if string(a.AgentsMD) != string(b.AgentsMD) {
		t.Error("AGENTS.md differs across two calls with an equal recipe")
	}
	if string(a.Architecture) != string(b.Architecture) {
		t.Error("architecture.json differs across two calls with an equal recipe")
	}
}

func TestGenerateMatchesGoldenFiles(t *testing.T) {
	t.Parallel()
	out, err := agentsfile.Generate(fullRecipe())
	if err != nil {
		t.Fatalf("Generate: %v", err)
	}

	wantMD, err := os.ReadFile("testdata/AGENTS.golden.md")
	if err != nil {
		t.Fatalf("read golden AGENTS.md: %v", err)
	}
	if string(out.AgentsMD) != string(wantMD) {
		t.Errorf("AGENTS.md does not match testdata/AGENTS.golden.md\ngot:\n%s", out.AgentsMD)
	}

	wantArch, err := os.ReadFile("testdata/architecture.golden.json")
	if err != nil {
		t.Fatalf("read golden architecture.json: %v", err)
	}
	if string(out.Architecture) != string(wantArch) {
		t.Errorf("architecture.json does not match testdata/architecture.golden.json\ngot:\n%s", out.Architecture)
	}
}

func TestGenerateNoModulesSelected(t *testing.T) {
	t.Parallel()
	r := fullRecipe()
	r.Modules = nil

	out, err := agentsfile.Generate(r)
	if err != nil {
		t.Fatalf("Generate: %v", err)
	}
	if !strings.Contains(string(out.AgentsMD), "Selected modules: none.") {
		t.Errorf("AGENTS.md does not report no modules selected:\n%s", out.AgentsMD)
	}

	var arch map[string]any
	if err := json.Unmarshal(out.Architecture, &arch); err != nil {
		t.Fatalf("architecture.json does not parse: %v", err)
	}
	for _, m := range arch["modules"].([]any) {
		mod := m.(map[string]any)
		if mod["selected"].(bool) {
			t.Errorf("module %v reported selected with an empty recipe.Modules", mod["name"])
		}
	}
}

func TestGeneratedFilesAreSelfConsistent(t *testing.T) {
	t.Parallel()
	root := t.TempDir()

	result, err := agentsfile.Write(root, fullRecipe(), false)
	if err != nil {
		t.Fatalf("Write: %v", err)
	}

	agentsData, err := os.ReadFile(result.AgentsPath)
	if err != nil {
		t.Fatalf("read %s: %v", result.AgentsPath, err)
	}
	if !strings.HasPrefix(string(agentsData), "<!-- Code generated by nise; DO NOT EDIT. -->\n") {
		t.Error("AGENTS.md is missing its ownership header")
	}

	archData, err := os.ReadFile(result.ArchitecturePath)
	if err != nil {
		t.Fatalf("read %s: %v", result.ArchitecturePath, err)
	}
	var arch struct {
		Generated string `json:"generated"`
	}
	if err := json.Unmarshal(archData, &arch); err != nil {
		t.Fatalf("architecture.json does not parse: %v", err)
	}
	if arch.Generated != agentsfile.ArchitectureGeneratedMarker {
		t.Errorf("architecture.json generated field = %q, want %q", arch.Generated, agentsfile.ArchitectureGeneratedMarker)
	}
}

