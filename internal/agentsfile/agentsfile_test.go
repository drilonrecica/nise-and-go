func TestWriteForceOverwritesHandEditedFiles(t *testing.T) {
	t.Parallel()
	root := t.TempDir()
	r := fullRecipe()

	result, err := agentsfile.Write(root, r, false)
	if err != nil {
		t.Fatalf("first Write: %v", err)
	}
	if err := os.WriteFile(result.AgentsPath, []byte("not what nise generated"), 0o644); err != nil {
		t.Fatal(err)
	}

	if _, err := agentsfile.Write(root, r, true); err != nil {
		t.Fatalf("Write with force=true = %v, want success", err)
	}

	data, err := os.ReadFile(result.AgentsPath)
	if err != nil {
		t.Fatal(err)
	}
	if strings.Contains(string(data), "not what nise generated") {
		t.Error("force=true did not overwrite the hand-edited content")
	}
}

func TestWriteBothConflictsReportedTogether(t *testing.T) {
	t.Parallel()
	root := t.TempDir()
	r := fullRecipe()

	result, err := agentsfile.Write(root, r, false)
	if err != nil {
		t.Fatalf("first Write: %v", err)
	}
	if err := os.WriteFile(result.AgentsPath, []byte("tampered"), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(result.ArchitecturePath, []byte("also tampered"), 0o644); err != nil {
		t.Fatal(err)
	}

	_, err = agentsfile.Write(root, r, false)
	var conflictErr *agentsfile.ConflictError
	if !errors.As(err, &conflictErr) {
		t.Fatalf("Write = %v, want *ConflictError", err)
	}
	if len(conflictErr.Conflicts) != 2 {
		t.Fatalf("Conflicts = %+v, want exactly two entries", conflictErr.Conflicts)
	}
}

