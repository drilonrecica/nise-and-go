// --- helpers ---------------------------------------------------------------

// stale ages the recipe so an upgrade has something to do.
func stale(t *testing.T, root string) {
	t.Helper()
	r := readRecipe(t, root)
	r.CLIVersion = "v0.0.1"
	r.RuntimeVersion = "v0.0.1"
	writeRecipe(t, root, r)
}

func readRecipe(t *testing.T, root string) recipe.Recipe {
	t.Helper()
	data, err := os.ReadFile(filepath.Join(root, recipe.FileName)) // #nosec G304 -- a path under this test's own t.TempDir().
	if err != nil {
		t.Fatalf("reading the recipe: %v", err)
	}
	r, err := recipe.Unmarshal(data)
	if err != nil {
		t.Fatalf("parsing the recipe: %v", err)
	}
	return r
}

func writeRecipe(t *testing.T, root string, r recipe.Recipe) {
	t.Helper()
	encoded, err := recipe.Marshal(r)
	if err != nil {
		t.Fatalf("encoding the recipe: %v", err)
	}
	write(t, root, recipe.FileName, string(encoded))
}

func mentions(changes []upgrade.FileChange, path string, action upgrade.Action) bool {
	for _, change := range changes {
		if change.Path == path && change.Action == action {
			return true
		}
	}
	return false
}

func anyContains(lines []string, want string) bool {
	for _, line := range lines {
		if strings.Contains(line, want) {
			return true
		}
	}
	return false
}

func anyStep(steps []string, want string) bool {
	for _, step := range steps {
		if step == want {
			return true
		}
	}
	return false
}

// snapshot renders every file's path and content hash, so a test can assert a
// tree is byte-identical before and after.
func snapshot(t *testing.T, root string) string {
	t.Helper()
	var b strings.Builder
	err := filepath.WalkDir(root, func(path string, entry os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if entry.IsDir() {
			return nil
		}
		relative, relErr := filepath.Rel(root, path)
		if relErr != nil {
			return relErr
		}
		info, infoErr := entry.Info()
		if infoErr != nil {
			return infoErr
		}
		b.WriteString(filepath.ToSlash(relative))
		b.WriteString(":")
		b.WriteString(info.Mode().String())
		b.WriteString(":")
		b.WriteString(strings.TrimSpace(itoa(info.Size())))
		b.WriteString("\n")
		return nil
	})
	if err != nil {
		t.Fatalf("walking the project: %v", err)
	}
	return b.String()
}

func itoa(n int64) string {
	if n == 0 {
		return "0"
	}
	var digits []byte
	for n > 0 {
		digits = append([]byte{byte('0' + n%10)}, digits...)
		n /= 10
	}
	return string(digits)
}

// Every write goes through an os.Root opened on the project, so a path can
// only resolve inside it. The paths come from this repository's own generator,
// so this is not defence against an attacker — it is defence against the thing
// that actually happens: a symlink somebody put inside their project, and a
// command that writes into a developer's working tree having no business being
// able to reach outside it.
func TestAnUpgradeCannotWriteOutsideTheProject(t *testing.T) {
	t.Parallel()
	root := newProject(t)

	outside := filepath.Join(filepath.Dir(root), "outside")
	if err := os.MkdirAll(outside, 0o750); err != nil {
		t.Fatalf("creating the outside directory: %v", err)
	}
	const sentinel = "the application's own file, untouched\n"
	// #nosec G703 -- a path beside this test's own t.TempDir() project.
	if err := os.WriteFile(filepath.Join(outside, "modules.gen.go"), []byte(sentinel), 0o600); err != nil {
		t.Fatalf("writing the sentinel: %v", err)
	}

	// Replace a Nise-owned *file* with a symlink out of the project, leaving
	// its directory a real one. A symlinked directory would be caught earlier,
	// when the parent directory is created; this is the case where every step
	// before the write looks ordinary.
	target := filepath.Join(root, "internal", "app", "modules.gen.go")
	if err := os.Remove(target); err != nil {
		t.Fatalf("removing %s: %v", target, err)
	}
	if err := os.Symlink(filepath.Join(outside, "modules.gen.go"), target); err != nil {
		t.Skipf("this filesystem does not support symlinks: %v", err)
	}
	stale(t, root)

	// Failing is a fine outcome, and so is succeeding without following the
	// link. What must not happen is the sentinel changing.
	_, _ = upgrade.Apply(options(root))

	after, err := os.ReadFile(filepath.Join(outside, "modules.gen.go")) // #nosec G304 -- a path this test just wrote.
	if err != nil {
		t.Fatalf("reading the sentinel: %v", err)
	}
	if string(after) != sentinel {
		t.Errorf("the upgrade wrote through a symlink and out of the project:\n%s", after)
	}
}
